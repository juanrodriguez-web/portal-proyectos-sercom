import "server-only";

// Parser CSV manual, sin dependencias externas. Deliberado: la
// alternativa obvia para CSV/XLSX en npm ("xlsx"/SheetJS) tiene CVEs
// abiertos sin fix (prototype pollution + ReDoS, GHSA-4r6h-8v6p-xvw6 y
// GHSA-5pgg-2g8v-p4x9) justo en el vector que mas importa aqui:
// parsear archivos subidos por usuarios. Hasta que haya una libreria
// XLSX confiable, la importacion solo soporta CSV.
export function parseCsv(text: string): Record<string, string>[] {
  const lines = text.split(/\r?\n/).filter((l) => l.length > 0);
  if (lines.length === 0) return [];

  const headers = splitCsvLine(lines[0]).map((h) => h.trim());
  return lines.slice(1).map((line) => {
    const cells = splitCsvLine(line);
    const row: Record<string, string> = {};
    headers.forEach((h, i) => {
      row[h] = (cells[i] ?? "").trim();
    });
    return row;
  });
}

function splitCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQuotes) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (c === '"') {
        inQuotes = false;
      } else {
        cur += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      out.push(cur);
      cur = "";
    } else {
      cur += c;
    }
  }
  out.push(cur);
  return out;
}
